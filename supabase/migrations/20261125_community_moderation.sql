create or replace function public.community_owner_stats(p_days integer default 30)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, auth
as $$
declare
  v_days integer := greatest(1, least(coalesce(p_days, 30), 365));
  v_start timestamptz := (current_date - (v_days - 1))::timestamptz;
begin
  if not public.is_community_owner() then
    raise exception 'Community owner access required.' using errcode = '42501';
  end if;

  return jsonb_build_object(
    'days', v_days,
    'totals', public.community_public_stats(),
    'daily', coalesce((
      select jsonb_agg(jsonb_build_object(
        'date', d.day::date,
        'visits', coalesce(v.visits, 0),
        'unique_visitors', coalesce(v.unique_visitors, 0),
        'logins', coalesce(l.logins, 0),
        'new_members', coalesce(m.new_members, 0),
        'reviews', coalesce(r.reviews, 0),
        'chat', coalesce(c.chat, 0)
      ) order by d.day)
      from generate_series(v_start, now(), interval '1 day') as d(day)
      left join (
        select date_trunc('day', created_at)::date as day,
               count(*)::int as visits,
               count(distinct visitor_hash)::int as unique_visitors
        from public.site_visits
        where created_at >= v_start
        group by 1
      ) v on v.day = d.day::date
      left join (
        select date_trunc('day', created_at)::date as day,
               count(*)::int as logins
        from public.community_login_events
        where created_at >= v_start
        group by 1
      ) l on l.day = d.day::date
      left join (
        select date_trunc('day', created_at)::date as day,
               count(*)::int as new_members
        from public.community_profiles
        where created_at >= v_start
        group by 1
      ) m on m.day = d.day::date
      left join (
        select date_trunc('day', created_at)::date as day,
               count(*)::int as reviews
        from public.reviews
        where created_at >= v_start
        group by 1
      ) r on r.day = d.day::date
      left join (
        select date_trunc('day', created_at)::date as day,
               count(*)::int as chat
        from public.chat_messages
        where created_at >= v_start
        group by 1
      ) c on c.day = d.day::date
    ), '[]'::jsonb),
    'providers', coalesce((
      select jsonb_agg(jsonb_build_object('provider', provider, 'count', count) order by count desc)
      from (
        select coalesce(nullif(provider, ''), 'unknown') as provider,
               count(*)::int as count
        from public.community_login_events
        where created_at >= v_start
        group by 1
      ) x
    ), '[]'::jsonb),
    'top_paths', coalesce((
      select jsonb_agg(jsonb_build_object('path', path, 'count', count) order by count desc)
      from (
        select path, count(*)::int as count
        from public.site_visits
        where created_at >= v_start
        group by path
        order by count(*) desc
        limit 8
      ) x
    ), '[]'::jsonb),
    'recent_members', coalesce((
      select jsonb_agg(jsonb_build_object(
        'username', username,
        'display_name', display_name,
        'provider', provider,
        'joined_at', created_at
      ) order by created_at desc)
      from (
        select username, display_name, provider, created_at
        from public.community_profiles
        order by created_at desc
        limit 8
      ) x
    ), '[]'::jsonb),
    'moderation', jsonb_build_object(
      'open_reports', (select count(*) from public.community_reports where status = 'open'),
      'active_bans', (
        select count(*)
        from public.community_bans
        where active and (expires_at is null or expires_at > now())
