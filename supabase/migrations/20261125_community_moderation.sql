create or replace function public.community_update_profile(
  p_display_name text,
  p_bio text
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_display text := left(btrim(coalesce(p_display_name, '')), 60);
  v_bio text := left(btrim(coalesce(p_bio, '')), 300);
begin
  if auth.uid() is null then
    raise exception 'Authentication required.' using errcode = '42501';
  end if;
  if char_length(v_display) < 1 then
    raise exception 'Display name cannot be empty.' using errcode = 'PT400';
  end if;

  perform public.ensure_community_profile(auth.uid());

  update public.community_profiles
  set display_name = v_display,
      bio = v_bio,
      updated_at = now()
  where user_id = auth.uid();

  return public.community_get_my_profile();
end;
$$;

create or replace function public.community_change_username(p_username text)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_username text := btrim(coalesce(p_username, ''));
  p public.community_profiles%rowtype;
begin
  if auth.uid() is null then
    raise exception 'Authentication required.' using errcode = '42501';
  end if;
  if v_username !~ '^[A-Za-z0-9_]{3,20}$' then
    raise exception 'Username must be 3–20 characters using letters, numbers or underscores.'
      using errcode = 'PT400';
  end if;
  if lower(v_username) in (
    'admin', 'administrator', 'owner', 'support', 'moderator',
    'system', 'extreme', 'pandeyji', 'pandeyji9'
  ) then
    raise exception 'That username is reserved.' using errcode = 'PT400';
  end if;

  perform public.ensure_community_profile(auth.uid());

  select * into p
  from public.community_profiles
  where user_id = auth.uid();

  if not found then
    raise exception 'Community profile was not found.' using errcode = 'PT404';
  end if;

  if lower(p.username) = lower(v_username) then
    return public.community_get_my_profile();
  end if;

  if p.username_changed_at is not null
    and p.username_changed_at > now() - interval '30 days' then
    raise exception 'Username can be changed once every 30 days.' using errcode = 'PT429';
  end if;

  if exists (
    select 1
    from public.community_profiles
    where lower(username) = lower(v_username)
      and user_id <> auth.uid()
  ) then
    raise exception 'That username is already taken.' using errcode = 'PT409';
  end if;

  update public.community_profiles
  set username = v_username,
      username_changed_at = now(),
      updated_at = now()
  where user_id = auth.uid();

  update public.reviews
  set author_username = v_username
  where user_id = auth.uid();

  update public.bug_reports
  set author_username = v_username
  where user_id = auth.uid();

  update public.chat_messages
