-- 4. Profile creation
-- ------------------------------------------------------------
create or replace function public.ensure_community_profile(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  u auth.users%rowtype;
  v_base text;
  v_username text;
  v_display text;
  v_avatar text;
  v_provider text;
  i integer;
begin
  if p_user_id is null then
    return;
  end if;

  if exists (
    select 1 from public.community_profiles where user_id = p_user_id
  ) then
    return;
  end if;

  select * into u
  from auth.users
  where id = p_user_id;

  if not found then
    return;
  end if;

  v_base := lower(coalesce(
    nullif(u.raw_user_meta_data ->> 'user_name', ''),
    nullif(u.raw_user_meta_data ->> 'preferred_username', ''),
    nullif(split_part(coalesce(u.email, ''), '@', 1), ''),
    'user'
  ));
  v_base := regexp_replace(v_base, '[^a-z0-9_]+', '', 'g');
  v_base := left(v_base, 12);
  if v_base = '' then
    v_base := 'user';
  end if;
  if v_base ~ '^[0-9]' then
    v_base := 'u' || v_base;
  end if;
  v_base := rpad(v_base, 3, '0');

  v_display := left(coalesce(
    nullif(u.raw_user_meta_data ->> 'full_name', ''),
    nullif(u.raw_user_meta_data ->> 'name', ''),
    nullif(u.raw_user_meta_data ->> 'user_name', ''),
    nullif(u.raw_user_meta_data ->> 'preferred_username', ''),
    nullif(split_part(coalesce(u.email, ''), '@', 1), ''),
    'Rider'
  ), 60);

  v_avatar := nullif(coalesce(
    u.raw_user_meta_data ->> 'avatar_url',
    u.raw_user_meta_data ->> 'picture'
  ), '');
  if v_avatar is not null and v_avatar !~ '^https?://' then
    v_avatar := null;
  end if;
  v_avatar := left(v_avatar, 500);

  select coalesce(
    (
      select i.provider
      from auth.identities i
      where i.user_id = u.id
      order by i.last_sign_in_at desc nulls last
      limit 1
    ),
    nullif(u.raw_app_meta_data ->> 'provider', '')
  ) into v_provider;

  v_username := v_base || '_' || substr(replace(u.id::text, '-', ''), 1, 6);

  for i in 1..20 loop
    begin
      insert into public.community_profiles (
        user_id, username, display_name, avatar_url, provider, created_at
      )
      values (
        u.id, v_username, v_display, v_avatar, v_provider,
        coalesce(u.created_at, now())
      )
      on conflict (user_id) do nothing;
      return;
    exception when unique_violation then
      v_username := left(v_base, 10) || '_' || substr(md5(u.id::text || i::text), 1, 8);
    end;
  end loop;

  raise exception 'Could not generate a unique community username.'
    using errcode = 'PT500';
end;
$$;

create or replace function public.handle_new_community_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  perform public.ensure_community_profile(new.id);
  return new;
end;
$$;

revoke all on function public.ensure_community_profile(uuid)
  from public, anon, authenticated;
