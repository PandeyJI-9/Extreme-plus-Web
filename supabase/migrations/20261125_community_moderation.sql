create or replace function public.guard_community_ban()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  actor uuid := auth.uid();
  target_role text;
begin
  if actor is null then
    if tg_op = 'INSERT' then
      new.created_at := coalesce(new.created_at, now());
      new.updated_at := coalesce(new.updated_at, now());
      new.active := coalesce(new.active, true);
    elsif tg_op = 'UPDATE' then
      new.updated_at := now();
    end if;
    return new;
  end if;

  if not public.is_community_admin() then
    raise exception 'Community admin access required.' using errcode = '42501';
  end if;

  if tg_op = 'UPDATE' and new.user_id <> old.user_id then
    raise exception 'A ban target cannot be changed.' using errcode = 'PT400';
  end if;

  if tg_op = 'UPDATE' and not new.active then
    new.lifted_at := coalesce(new.lifted_at, now());
    new.lifted_by := coalesce(new.lifted_by, actor);
    new.updated_at := now();
    return new;
  end if;

  if new.user_id = actor then
    raise exception 'You cannot ban your own account.' using errcode = 'PT400';
  end if;

  select role into target_role
  from public.community_admins
  where user_id = new.user_id;

  if target_role = 'owner' then
    raise exception 'The owner cannot be banned.' using errcode = 'PT400';
  end if;
  if target_role = 'admin' and not public.is_community_owner() then
    raise exception 'Only the owner can ban an admin.' using errcode = 'PT400';
  end if;
  if new.expires_at is not null and new.expires_at <= now() then
    raise exception 'Ban expiry must be in the future.' using errcode = 'PT400';
  end if;

  if tg_op = 'INSERT' then
    new.banned_by := actor;
    new.created_at := now();
    new.updated_at := now();
    new.active := true;
    new.lifted_at := null;
    new.lifted_by := null;
  else
    new.banned_by := actor;
    new.updated_at := now();
    new.lifted_at := null;
    new.lifted_by := null;
  end if;

  return new;
end;
$$;

create or replace function public.guard_community_admin()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  actor uuid := auth.uid();
  owner_count integer;
begin
  if actor is null then
    if tg_op = 'DELETE' then
      return old;
    end if;
    new.updated_at := now();
    return new;
  end if;

  if not public.is_community_owner() then
    raise exception 'Community owner access required.' using errcode = '42501';
  end if;

  if tg_op = 'INSERT' then
    if new.role not in ('owner', 'admin') then
      raise exception 'Invalid admin role.' using errcode = 'PT400';
    end if;
    new.created_by := actor;
    new.created_at := now();
    new.updated_at := now();
    return new;
  end if;

  if tg_op = 'UPDATE' then
    if new.user_id <> old.user_id then
      raise exception 'An admin target cannot be changed.' using errcode = 'PT400';
    end if;
    if new.role not in ('owner', 'admin') then
      raise exception 'Invalid admin role.' using errcode = 'PT400';
    end if;
    if old.role = 'owner' and new.role <> 'owner' then
      select count(*) into owner_count
      from public.community_admins
      where role = 'owner';
      if owner_count <= 1 then
        raise exception 'The last owner cannot be demoted.' using errcode = 'PT400';
      end if;
    end if;
    new.updated_at := now();
    return new;
  end if;

  if tg_op = 'DELETE' then
    if old.role = 'owner' then
      select count(*) into owner_count
      from public.community_admins
      where role = 'owner';
      if owner_count <= 1 then
        raise exception 'The last owner cannot be removed.' using errcode = 'PT400';
      end if;
    end if;
    return old;
  end if;

  return new;
end;
$$;

