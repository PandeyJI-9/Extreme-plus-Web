        'username', old.author_username,
        'title', left(old.title, 120),
        'old_status', old.status,
        'new_status', new.status
      )
    );
  end if;
  return new;
end;
$$;

create or replace function public.log_community_report_status()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if new.status is distinct from old.status then
    insert into public.community_moderation_log (
      actor_id, action, target_user_id, target_table, target_id, details
    )
    values (
      auth.uid(),
      'report_' || new.status,
      new.target_user_id,
      'community_reports',
      new.id::text,
      jsonb_build_object(
        'target_type', new.target_type,
        'target_id', new.target_id,
        'reason', left(new.reason, 240)
      )
    );
  end if;
  return new;
end;
$$;

